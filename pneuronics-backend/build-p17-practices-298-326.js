// Generates practice-defs/practices-298-326.js: three practice problems per rebuilt Phase 17 lesson (modules 298-326),
// grounded in each lesson's lab file and its "Genuinely Found" findings. Also exports the stale practices it replaces.
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const mongoose = require('mongoose');
const { Lesson, Module, Practice } = require('./models/Curriculum');
const ext = require('./practice-defs/p17-extensions-298-326.js');

const PHASE = '6a369d6066020ed05b32150b';
const strip = (s) => (s || '').replace(/^Genuinely Found:\s*/, '').replace(/^ನಿಜವಾಗಿ ಕಂಡುಬಂದದ್ದು:\s*/, '').trim();
const tail = (s) => { const i = (s || '').indexOf(' — '); return i >= 0 ? s.slice(i + 3) : s; };
const parse = (s) => { try { return JSON.parse(s || '[]'); } catch { return []; } };

async function main() {
  await mongoose.connect(process.env.MONGODB_URI);
  const mods = await Module.find({ phaseId: PHASE, order: { $gte: 298, $lte: 326 } }).sort({ order: 1 }).lean();
  const defs = [], stale = [];
  for (const mod of mods) {
    const lessons = await Lesson.find({ moduleId: String(mod._id) }).sort({ order: 1 }).lean();
    for (const l of lessons) {
      const en = parse(l.builderEn), kn = parse(l.builderKn);
      const file = [...new Set(en.filter((b) => b.type === 'code').map((b) => b.data.filename))][0];
      if (!file || !fs.existsSync(path.join(__dirname, 'lesson-defs/labs', file))) throw new Error(`lab file missing for ${mod.order}.${l.order}: ${file}`);
      const gs = en.map((b, i) => [b, i]).filter(([b]) => b.type === 'concept' && /^Genuinely/.test(b.data.headingEn || ''))
        .map(([b, i]) => ({ en: strip(b.data.headingEn), kn: strip(b.data.headingKn || (kn[i] && kn[i].data.headingKn)) }));
      if (!gs.length) throw new Error(`no findings for ${mod.order}.${l.order}`);
      const g1 = gs[0], g2 = gs[1] || gs[0];
      const key = `${mod.order}.${l.order}`;
      if (!ext[key]) throw new Error('no extension for ' + key);
      const sub = tail(l.title), subKn = tail(l.titleKn);
      const base = { phaseId: PHASE, moduleId: String(mod._id), lessonId: String(l._id), status: 'published' };
      const same = g1 === g2;
      defs.push(
        { ...base, order: 1, difficulty: 'intermediate',
          title: `Reproduce: ${g1.en}`, titleKn: `ಪುನರುತ್ಪಾದಿಸಿ: ${g1.kn}`,
          problem: `Run \`python -B ${file}\` from pneuronics-backend/lesson-defs/labs and find the finding "${g1.en}".\n1. Copy the output lines that show it.\n2. Explain in two or three sentences why it happens, naming the function or class in the lab that is responsible.\n3. Describe one realistic situation where ignoring this behaviour would give a wrong result in a real agent.`,
          problemKn: `pneuronics-backend/lesson-defs/labs ನಿಂದ \`python -B ${file}\` ಚಲಾಯಿಸಿ ಮತ್ತು "${g1.kn}" ಎಂಬ ಕಂಡುಹಿಡಿಕೆಯನ್ನು ಹುಡುಕಿ.\n1. ಅದನ್ನು ತೋರಿಸುವ output ಸಾಲುಗಳನ್ನು ನಕಲಿಸಿ.\n2. ಅದು ಏಕೆ ಆಗುತ್ತದೆ ಎಂದು ಎರಡು ಅಥವಾ ಮೂರು ವಾಕ್ಯಗಳಲ್ಲಿ ವಿವರಿಸಿ, ಲ್ಯಾಬ್‌ನಲ್ಲಿ ಜವಾಬ್ದಾರಿಯುತ ಕಾರ್ಯ ಅಥವಾ ವರ್ಗದ ಹೆಸರು ಹೇಳಿ.\n3. ಈ ವರ್ತನೆಯನ್ನು ನಿರ್ಲಕ್ಷಿಸಿದರೆ ನಿಜ agent ನಲ್ಲಿ ತಪ್ಪು ಫಲಿತಾಂಶ ಬರುವ ಒಂದು ವಾಸ್ತವಿಕ ಸಂದರ್ಭ ವಿವರಿಸಿ.` },
        { ...base, order: 2, difficulty: 'intermediate',
          title: `Test and fix: ${g2.en}`, titleKn: `ಪರೀಕ್ಷೆ ಮತ್ತು ಸರಿಪಡಿಕೆ: ${g2.kn}`,
          problem: `Write a small test (plain assert statements in Python) for the behaviour in "${g2.en}"${same ? ' (this lesson has one main finding, so look at a different line of its output than in the first problem)' : ''}.\n1. The test must fail on the lab's current code, or show the problem clearly.\n2. Fix the code so the test passes, without weakening the test.\n3. State one case your test does not cover.`,
          problemKn: `"${g2.kn}" ನಲ್ಲಿನ ವರ್ತನೆಗೆ ಚಿಕ್ಕ ಪರೀಕ್ಷೆ (Python ನ ಸಾದಾ assert ಹೇಳಿಕೆಗಳು) ಬರೆಯಿರಿ${same ? ' (ಈ ಲೆಸನ್‌ಗೆ ಒಂದೇ ಮುಖ್ಯ ಕಂಡುಹಿಡಿಕೆ ಇದೆ, ಆದ್ದರಿಂದ ಮೊದಲ ಸಮಸ್ಯೆಗಿಂತ ಅದರ output ನ ಬೇರೆ ಸಾಲನ್ನು ನೋಡಿ)' : ''}.\n1. ಪರೀಕ್ಷೆ ಲ್ಯಾಬ್‌ನ ಈಗಿನ ಕೋಡ್‌ನಲ್ಲಿ ವಿಫಲವಾಗಬೇಕು, ಅಥವಾ ಸಮಸ್ಯೆಯನ್ನು ಸ್ಪಷ್ಟವಾಗಿ ತೋರಿಸಬೇಕು.\n2. ಪರೀಕ್ಷೆ ಪಾಸ್ ಆಗುವಂತೆ ಕೋಡ್ ಸರಿಪಡಿಸಿ, ಪರೀಕ್ಷೆಯನ್ನು ದುರ್ಬಲಗೊಳಿಸದೆ.\n3. ನಿಮ್ಮ ಪರೀಕ್ಷೆ ಆವರಿಸದ ಒಂದು ಪ್ರಕರಣ ಹೇಳಿ.` },
        { ...base, order: 3, difficulty: 'advanced',
          title: `Extend: ${sub}`, titleKn: `ವಿಸ್ತರಿಸಿ: ${subKn}`,
          problem: `In \`${file}\`: ${ext[key][0]}\nReport what you changed, the output before and after, and one case your change still does not handle.`,
          problemKn: `\`${file}\` ನಲ್ಲಿ: ${ext[key][1]}\nನೀವು ಏನು ಬದಲಿಸಿದಿರಿ, ಮೊದಲು ಮತ್ತು ನಂತರದ output, ಮತ್ತು ನಿಮ್ಮ ಬದಲಾವಣೆ ಇನ್ನೂ ನಿರ್ವಹಿಸದ ಒಂದು ಪ್ರಕರಣ ವರದಿ ಮಾಡಿ.` });
      const old = await Practice.find({ lessonId: String(l._id) }).lean();
      stale.push(...old);
    }
  }
  const out = path.join(__dirname, 'practice-defs/practices-298-326.js');
  fs.writeFileSync(out, '// Generated by build-p17-practices.js. Three practices per rebuilt lesson (modules 298-326).\nmodule.exports = ' + JSON.stringify(defs, null, 1) + ';\n');
  const bdir = path.join(__dirname, 'lesson-defs/backups/phase17-before-rebuild');
  fs.writeFileSync(path.join(bdir, 'stale-practices-298-326.json'), JSON.stringify(stale));
  console.log('definitions:', defs.length, '| stale practices exported:', stale.length, '| lessons:', defs.length / 3);
  await mongoose.disconnect();
}
main().catch((e) => { console.error(e); process.exit(1); });
