"""Teaching implementation (our own): eval-driven agent development, Part 3 - aggregating case results into a suite report, a release policy with category and critical
gates, coverage checks, an ERROR status for an empty suite, a real process exit code, paired candidate comparison and failure injection into the gate. Results are
generated by a seeded stand-in for an agent; no language model is involved."""
import json
import random
import subprocess
import sys
from collections import defaultdict
from dataclasses import dataclass


@dataclass(frozen=True)
class Res:
    name: str
    category: str
    severity: str
    passed: bool
    attempts: int


@dataclass(frozen=True)
class Report:
    total: int
    passed: int
    pass_rate: float
    first_pass_rate: float
    repair_rate: float
    mean_attempts: float


def build_report(rs):
    if not rs:
        return None
    n = len(rs)
    passed = sum(r.passed for r in rs)
    first_ok = sum(r.passed and r.attempts == 1 for r in rs)
    first_fail = [r for r in rs if not (r.passed and r.attempts == 1)]
    repaired = sum(r.passed for r in first_fail)
    return Report(n, passed, passed / n, first_ok / n, repaired / len(first_fail) if first_fail else 1.0, sum(r.attempts for r in rs) / n)


def category_rates(rs):
    g = defaultdict(list)
    for r in rs:
        g[r.category].append(r.passed)
    return {k: sum(v) / len(v) for k, v in g.items()}


POLICY = dict(min_rate=0.90, max_regression=0.01, max_attempts=2.0, categories={"security": 1.0, "tool_use": 0.95}, min_cases={"security": 5, "tool_use": 5})


def gate(rs, baseline_rate, policy=POLICY):
    """Returns (status, reasons). Status is PASS, FAIL or ERROR (the evidence itself is unusable)."""
    if not rs:
        return "ERROR", ["no evaluation cases were loaded"]
    reasons, rep, cats = [], build_report(rs), category_rates(rs)
    if rep.pass_rate < policy["min_rate"]:
        reasons.append(f"pass rate {rep.pass_rate:.1%} below {policy['min_rate']:.0%}")
    if rep.pass_rate < baseline_rate - policy["max_regression"]:
        reasons.append("regressed beyond tolerance against the baseline")
    if rep.mean_attempts > policy["max_attempts"]:
        reasons.append(f"mean attempts {rep.mean_attempts:.2f} over budget")
    crit = [r.name for r in rs if r.severity == "critical" and not r.passed]
    if crit:
        reasons.append(f"critical failures: {crit}")
    errors = []
    for c, need in policy["categories"].items():
        if c not in cats:
            errors.append(f"missing category {c}")
        elif sum(1 for r in rs if r.category == c) < policy["min_cases"][c]:
            errors.append(f"category {c} has too few cases")
        elif cats[c] < need:
            reasons.append(f"{c} rate {cats[c]:.0%} below {need:.0%}")
    if errors:
        return "ERROR", errors + reasons
    return ("PASS" if not reasons else "FAIL"), reasons


def make_suite(seed, p_by_cat, n_by_cat, crit_cat="security"):
    rng = random.Random(seed)
    out, k = [], 0
    for cat, n in n_by_cat.items():
        for i in range(n):
            ok = rng.random() < p_by_cat[cat]
            attempts = 1 if ok and rng.random() < 0.8 else (2 if ok else 3)
            out.append(Res(f"{cat}-{i}", cat, "critical" if cat == crit_cat else "normal", ok, attempts))
    return out


def section(t):
    print(f"\n--- {t} ---")


def main():
    N = {"reasoning": 40, "tool_use": 20, "security": 10, "memory": 10}
    section("1. Genuinely computing: one suite report (seeded stand-in agent, assumed pass probabilities)")
    suite = make_suite(1, {"reasoning": 0.95, "tool_use": 0.97, "security": 1.0, "memory": 0.92}, N)
    rep = build_report(suite)
    print(rep)
    print({k: round(v, 3) for k, v in category_rates(suite).items()})
    print("first-pass success, repair rate and mean attempts come from the same results as the pass rate; two systems with the same final pass rate can differ a lot on these")

    section("2. Genuinely checking: gate decisions for a good candidate, a security regression and a critical failure")
    for label, probs in (("good candidate", {"reasoning": 0.97, "tool_use": 0.99, "security": 1.0, "memory": 0.95}), ("security regressed", {"reasoning": 0.99, "tool_use": 1.0, "security": 0.7, "memory": 0.99})):
        s = make_suite(2, probs, N)
        r = build_report(s)
        status, reasons = gate(s, baseline_rate=0.94)
        print(f"{label:20} overall {r.pass_rate:.1%}  gate={status} {reasons}")
    print("a candidate can have an overall rate that looks fine and still be blocked by the security gate and by its critical failures; averages are a summary, the gate is the decision")

    section("3. Genuinely checking: an empty or incomplete suite must not look like success")
    print("empty suite:", gate([], 0.9))
    partial = [r for r in make_suite(2, {"reasoning": 1.0, "tool_use": 1.0, "security": 1.0, "memory": 1.0}, N) if r.category != "security"]
    print("security cases missing:", gate(partial, 0.9))
    thin = [r for r in make_suite(2, {"reasoning": 1.0, "tool_use": 1.0, "security": 1.0, "memory": 1.0}, N) if r.category != "security"] + make_suite(9, {"security": 1.0}, {"security": 1})
    print("security collapsed to 1 case:", gate(thin, 0.9))
    print("each of these has no failing case, so a gate that only looks at failures would pass them; ERROR is a separate status that blocks because the evidence itself cannot be trusted")

    section("4. Genuinely checking: the gate as a real process exit code")
    code = (
        "import json,sys;d=json.loads(sys.argv[1]);print(json.dumps(d,sort_keys=True));sys.exit(0 if d['status']=='PASS' else 1 if d['status']=='FAIL' else 2)"
    )
    good = make_suite(2, {"reasoning": 0.99, "tool_use": 1.0, "security": 1.0, "memory": 1.0}, N)
    for label, s in (("good", good), ("empty", [])):
        status, reasons = gate(s, 0.94)
        p = subprocess.run([sys.executable, "-c", code, json.dumps({"status": status, "reasons": reasons})], capture_output=True, text=True)
        print(f"{label:6} printed {p.stdout.strip()[:90]} exit code {p.returncode}")
    print("0 means pass, 1 means the candidate failed policy and 2 means the evidence could not be used; CI acts on the exit code, so printing FAIL and exiting 0 would have let a bad build through")

    section("5. Genuinely measuring: paired comparison of two candidates on the same 100 cases (assumed pass probabilities, seed 4)")
    rng = random.Random(4)
    both = only_a = only_b = neither = 0
    for _ in range(100):
        a, b = rng.random() < 0.70, rng.random() < 0.85
        both += a and b; only_a += a and not b; only_b += b and not a; neither += not a and not b
    print(f"both pass {both}, only prompt-only passes {only_a}, only workbench passes {only_b}, neither {neither}; rates {both + only_a}% and {both + only_b}%")
    print("the paired table shows where the two candidates disagree, which two success percentages hide; with 100 cases the difference between rates still has noticeable uncertainty, and prompt-only wins are reported where they occur")

    section("6. Genuinely measuring: noise in a pass rate from a small suite (true rate ASSUMED at 0.92, seed 6)")
    rng = random.Random(6)
    for n in (20, 100, 1000):
        rates = sorted(sum(rng.random() < 0.92 for _ in range(n)) / n for _ in range(2000))
        print(f"{n:5} cases: observed pass rate ranged from {rates[50]:.1%} to {rates[1949]:.1%} across 95 percent of reruns with no real change")
    print("a 20-case suite can swing by more than the 1-point regression tolerance with nothing changing, so a tight tolerance needs either many cases or repeated runs")

    section("7. Genuinely checking: failure injection into the gate itself")
    def broken_gate(rs):
        return "PASS" if all(r.passed for r in rs) else "FAIL"  # forgets the empty and missing-evidence cases
    print("broken gate on an empty suite:", broken_gate([]), "| real gate:", gate([], 0.9)[0])
    print("broken gate on a suite with only passing normal cases and no security category:", broken_gate(partial), "| real gate:", gate(partial, 0.9)[0])
    print("the defective gate behaves correctly whenever a case fails and only goes wrong when evidence is empty or missing, so ordinary failing-case tests would never find it; injecting the empty and missing-category inputs is how the defect is found")


if __name__ == "__main__":
    main()
